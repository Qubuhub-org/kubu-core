# 1. Create the Kubu data directory if it doesn't exist
mkdir -p ~/.kubu

# 2. Open nano editor to create/paste the config file
nano ~/.kubu/kubu.conf

# 3. Paste the contents, press Ctrl+O -> Enter -> Ctrl+X to save and exit

# 4. Set secure file permissions (recommended)
chmod 600 ~/.kubu/kubu.conf
